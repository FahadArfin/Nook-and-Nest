def bead_mesh(box):
    """Sixteen-sided source-size reed: smooth sides, closed planar ends."""
    import math
    size=[box['max'][a]-box['min'][a] for a in range(3)]
    if not (.0099<size[0]<.0101 and .0097<size[1]<.0099 and .288<size[2]<.289):
        raise ValueError('Reviewed ten-millimetre drawer reed dimensions changed')
    cx,cy=[(box['min'][a]+box['max'][a])/2 for a in (0,1)]
    vertices=[(cx+size[0]*.5*math.cos(i*math.tau/16),cy+size[1]*.5*math.sin(i*math.tau/16),z)
              for z in (box['min'][2],box['max'][2]) for i in range(16)]
    faces=[(i,(i+1)%16,(i+1)%16+16,i+16) for i in range(16)]
    faces.extend([tuple(reversed(range(16))),tuple(range(16,32))])
    return vertices,faces


