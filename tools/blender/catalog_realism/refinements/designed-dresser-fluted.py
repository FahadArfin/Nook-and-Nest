def group_flute_evidence(changes):
    expected = [spec['name'] for spec in SOURCE_COMPONENTS]
    if (len(changes) != len(expected)
            or [record.get('component') for record in changes] != expected
            or any(record.get('kind') != 'source-evidenced-construction' for record in changes)):
        raise ValueError('Expected the complete ordered evidence for all 156 drawer flutes')
    return [{'kind': 'source-evidenced-construction', 'componentCount': len(changes),
             'construction': 'Bounded rounded drawer flute profiles with all measured component evidence retained',
             'components': changes}]


